#!/usr/bin/env node
// Generates the Rounded companion style from the "pi-rounded" (v2) terminal mascot pack:
// pi-rounded/frames.json, 48 x 52 pixels keyed by a shared palette (key 0 is transparent).
// The keys are kept as they are; only "0" becomes ".".
// Only the states the companion panel maps to working activities are exported, with each
// state's frame duration so the panel can follow the pack's timing on its own tick. Active
// states drop frames identical to the resting idle frame (the packs reuse it to enter and leave
// a pose), so a looping activity never flashes back to the idle pose.
//
// Usage: node scripts/generate-pi-pack-sprites.mjs <rounded frames.json> <out-dir>
// The pack can be read straight from its ZIP, for example:
//   node scripts/generate-pi-pack-sprites.mjs \
//     <(unzip -p pi-rounded-terminal-v2.zip pi-rounded/frames.json) \
//     extensions/osdy-pi
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";
import console from "node:console";

const STATES = ["idle", "think", "walk_right", "look", "walk_left", "wave", "jump"];

function fail(message) {
	console.error(message);
	process.exit(1);
}

function readJson(path) {
	try {
		return JSON.parse(readFileSync(path, "utf8"));
	} catch (error) {
		fail(`Cannot read ${path}: ${error instanceof Error ? error.message : String(error)}`);
	}
}

function parseHex(hex) {
	if (hex === null) return undefined;
	const match = /^#([0-9a-f]{6})$/i.exec(hex);
	if (!match) fail(`Invalid color ${JSON.stringify(hex)}`);
	const value = Number.parseInt(match[1], 16);
	return [(value >> 16) & 255, (value >> 8) & 255, value & 255];
}

function animation(pack, state) {
	const entry = pack.animations?.[state];
	if (!entry || !Array.isArray(entry.frames) || entry.frames.length === 0) fail(`Missing state ${state}`);
	const durations = new Set(entry.frames.map((frame) => frame.durationMs));
	if (durations.size !== 1) fail(`State ${state} mixes frame durations`);
	return { frames: entry.frames, durationMs: entry.frames[0].durationMs };
}

/** Rounded: palette-keyed pixel rows, used as they are. */
function roundedPack(pack) {
	if (pack.version !== 2 || pack.width !== 48 || pack.height !== 52) fail("Expected the 48 x 52 pi-rounded v2 frames.json");
	const palette = {};
	const states = {};
	const used = new Set();
	for (const state of STATES) {
		const { frames, durationMs } = animation(pack, state);
		states[state] = {
			durationMs,
			frames: frames.map((frame) => {
				if (frame.pixels.length !== pack.height) fail(`${state}: expected ${pack.height} rows`);
				return frame.pixels.map((row) => {
					if (row.length !== pack.width) fail(`${state}: expected ${pack.width} columns`);
					for (const key of row) {
						if (!(key in pack.palette)) fail(`${state}: unknown key ${key}`);
						if (key !== "0") used.add(key);
					}
					return row.replaceAll("0", ".");
				});
			}),
		};
	}
	for (const key of Object.keys(pack.palette)) {
		if (used.has(key)) palette[key] = parseHex(pack.palette[key]);
	}
	return { width: pack.width, height: pack.height, palette, states };
}

/** Drops active-state frames that repeat the resting idle frame. */
function withoutRestFrames(sprite) {
	const rest = sprite.states.idle.frames[0].join("\n");
	for (const state of STATES) {
		if (state === "idle") continue;
		const frames = sprite.states[state].frames.filter((frame) => frame.join("\n") !== rest);
		if (frames.length === 0) fail(`${state}: every frame repeats the idle pose`);
		sprite.states[state].frames = frames;
	}
	return sprite;
}

const STATE_NAMES = { walk_right: "walkRight", walk_left: "walkLeft" };

function moduleSource(name, constant, source, sprite) {
	const lines = [
		`// Generated by scripts/generate-pi-pack-sprites.mjs from ${source}. Do not edit by hand.`,
		"// Grids hold palette keys, \".\" for transparent; each terminal row shows two grid rows.",
		"",
		"import type { PixelRgb } from \"./pi-raccoon-sprites.js\";",
		"",
		`export const ${constant}_PALETTE: Readonly<Record<string, PixelRgb>> = {`,
		...Object.entries(sprite.palette).map(([key, [r, g, b]]) => `\t"${key}": [${r}, ${g}, ${b}],`),
		"};",
		"",
		`/** ${name} companion animations, ${sprite.width} x ${sprite.height} pixels each, with each state's frame duration. */`,
		`export const ${constant}_FRAMES = {`,
	];
	for (const state of STATES) {
		const { durationMs, frames } = sprite.states[state];
		lines.push(`\t${STATE_NAMES[state] ?? state}: {`, `\t\tdurationMs: ${durationMs},`, "\t\tframes: [");
		for (const frame of frames) {
			lines.push("\t\t\t[", ...frame.map((row) => `\t\t\t\t"${row}",`), "\t\t\t],");
		}
		lines.push("\t\t],", "\t},");
	}
	lines.push("} as const;", "");
	return lines.join("\n");
}

const [roundedPath, outDir] = process.argv.slice(2);
if (!roundedPath || !outDir) fail("Usage: node scripts/generate-pi-pack-sprites.mjs <rounded frames.json> <out-dir>");

const outputs = [
	["pi-rounded-sprites.ts", "Rounded", "PI_ROUNDED", "pi-rounded/frames.json", roundedPack(readJson(roundedPath))],
];
for (const [file, name, constant, source, sprite] of outputs) {
	writeFileSync(join(outDir, file), moduleSource(name, constant, source, withoutRestFrames(sprite)));
	console.log(`Wrote ${join(outDir, file)}`);
}
