#!/usr/bin/env node
// Generates the Terminal companion style from the "Pi Terminal" pack (pi-terminal/frames.json):
// its 24 x 24 grids of palette keys over a five-color palette, where "." is transparent. The
// pack's 16 x 16 variant is not used. The grids are kept as they are; this script only validates
// them and selects the states the companion panel maps to working activities.
// Idle keeps only its resting first frame, because the panel shows idle as a still pose. Active
// states must use one frame duration; they drop frames identical to that resting frame, so a
// looping activity never flashes back to the idle pose.
//
// Usage: node scripts/generate-pi-terminal-sprites.mjs <frames.json> <out-file>
// The pack can be read straight from its ZIP, for example:
//   node scripts/generate-pi-terminal-sprites.mjs \
//     <(unzip -p pi-terminal.zip pi-terminal/frames.json) \
//     extensions/osdy-pi/pi-terminal-sprites.ts
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import console from "node:console";

const ACTIVE_STATES = ["think", "walk_right", "eat", "walk_left", "wave", "jump"];
const VARIANTS = [
	{ key: "24", constant: "PI_TERMINAL_FRAMES", name: "Terminal", size: 24 },
];
const STATE_NAMES = { walk_right: "walkRight", walk_left: "walkLeft" };

function fail(message) {
	console.error(message);
	process.exit(1);
}

function readJson(path) {
	try {
		return JSON.parse(readFileSync(path, "utf8"));
	} catch (error) {
		fail(`Cannot read ${path}: ${error instanceof Error ? error.message : String(error)}`);
	}
}

function parseHex(key, hex) {
	const match = typeof hex === "string" ? /^#([0-9a-f]{6})$/i.exec(hex) : null;
	if (!match) fail(`Invalid color for key ${JSON.stringify(key)}: ${JSON.stringify(hex)}`);
	const value = Number.parseInt(match[1], 16);
	return [(value >> 16) & 255, (value >> 8) & 255, value & 255];
}

function palette(pack) {
	if (pack.transparent !== "." || pack.palette?.["."] !== null) fail("Expected \".\" as the transparent key");
	const entries = Object.entries(pack.palette).filter(([key]) => key !== ".");
	for (const [key] of entries) {
		if (key.length !== 1 || key === "\"" || key === "\\") fail(`Unsupported palette key ${JSON.stringify(key)}`);
	}
	return Object.fromEntries(entries.map(([key, hex]) => [key, parseHex(key, hex)]));
}

function frames(variant, state, size, colors) {
	const entry = variant.animations?.[state];
	if (!entry || !Array.isArray(entry.frames) || entry.frames.length === 0) fail(`${size}: missing state ${state}`);
	if (!Array.isArray(entry.duration_ms) || entry.duration_ms.length !== entry.frames.length) {
		fail(`${size} ${state}: expected one duration per frame`);
	}
	for (const frame of entry.frames) {
		if (!Array.isArray(frame) || frame.length !== size) fail(`${size} ${state}: expected ${size} rows`);
		for (const row of frame) {
			if (typeof row !== "string" || row.length !== size) fail(`${size} ${state}: expected ${size} columns`);
			for (const key of row) {
				if (key !== "." && !(key in colors)) fail(`${size} ${state}: unknown key ${JSON.stringify(key)}`);
			}
		}
	}
	return entry;
}

function variantStates(pack, { key, size }, colors) {
	const variant = pack.variants?.[key];
	if (!variant || variant.width !== size || variant.height !== size) fail(`Expected the ${size} x ${size} variant`);
	const idle = frames(variant, "idle", size, colors);
	const rest = idle.frames[0];
	const states = { idle: { durationMs: idle.duration_ms[0], frames: [rest] } };
	for (const state of ACTIVE_STATES) {
		const entry = frames(variant, state, size, colors);
		if (new Set(entry.duration_ms).size !== 1) fail(`${size} ${state}: mixes frame durations`);
		const kept = entry.frames.filter((frame) => frame.join("\n") !== rest.join("\n"));
		if (kept.length === 0) fail(`${size} ${state}: every frame repeats the idle pose`);
		states[STATE_NAMES[state] ?? state] = { durationMs: entry.duration_ms[0], frames: kept };
	}
	return states;
}

function moduleSource(colors, variants) {
	const lines = [
		"// Generated by scripts/generate-pi-terminal-sprites.mjs from pi-terminal/frames.json. Do not edit by hand.",
		"// Grids hold palette keys, \".\" for transparent; each terminal row shows two grid rows.",
		"",
		"import type { PixelRgb } from \"./pi-raccoon-sprites.js\";",
		"",
		"export const PI_TERMINAL_PALETTE: Readonly<Record<string, PixelRgb>> = {",
		...Object.entries(colors).map(([key, [r, g, b]]) => `\t"${key}": [${r}, ${g}, ${b}],`),
		"};",
	];
	for (const { constant, name, size, states } of variants) {
		lines.push(
			"",
			`/** ${name} companion animations, ${size} x ${size} pixels each, with each state's frame duration. Idle keeps its resting frame. */`,
			`export const ${constant} = {`,
		);
		for (const [state, { durationMs, frames: grids }] of Object.entries(states)) {
			lines.push(`\t${state}: {`, `\t\tdurationMs: ${durationMs},`, "\t\tframes: [");
			for (const grid of grids) lines.push("\t\t\t[", ...grid.map((row) => `\t\t\t\t"${row}",`), "\t\t\t],");
			lines.push("\t\t],", "\t},");
		}
		lines.push("} as const;");
	}
	lines.push("");
	return lines.join("\n");
}

const [framesPath, outFile] = process.argv.slice(2);
if (!framesPath || !outFile) fail("Usage: node scripts/generate-pi-terminal-sprites.mjs <frames.json> <out-file>");

const pack = readJson(framesPath);
if (pack.name !== "Pi Terminal" || pack.version !== 1) fail("Expected the Pi Terminal frames.json, version 1");
const colors = palette(pack);
const variants = VARIANTS.map((variant) => ({ ...variant, states: variantStates(pack, variant, colors) }));
writeFileSync(outFile, moduleSource(colors, variants));
console.log(`Wrote ${outFile}`);
