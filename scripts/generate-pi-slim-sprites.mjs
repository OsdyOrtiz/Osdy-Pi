#!/usr/bin/env node
// Generates the Slim and Pocket Ringtail companion styles from the "Pi Terminal v2" pack
// (pi-terminal-v2/frames.json): grids of palette keys over a five-color palette, where "." is
// transparent. The 24 x 24 variant becomes Slim Ringtail and the separately drawn 16 x 16
// variant becomes Pocket Ringtail. The grids are kept as they are; this script only validates
// them and selects the states the companion panel maps to working activities.
// Idle keeps only its resting first frame, because the panel shows idle as a still pose. Active
// states drop frames identical to that resting frame, so a looping activity never flashes back
// to the idle pose, and every kept frame keeps its own duration.
//
// Usage: node scripts/generate-pi-slim-sprites.mjs <frames.json> <out-file>
// The pack can be read straight from its ZIP, for example:
//   node scripts/generate-pi-slim-sprites.mjs \
//     <(unzip -p pi-terminal-v2.zip pi-terminal-v2/frames.json) \
//     extensions/osdy-pi/pi-slim-sprites.ts
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import console from "node:console";

const ACTIVE_STATES = ["think", "walk_right", "eat", "walk_left", "wave", "jump"];
const VARIANTS = [
	{ key: "24", constant: "PI_SLIM_FRAMES", name: "Slim Ringtail", size: 24 },
	{ key: "16", constant: "PI_SLIM_SMALL_FRAMES", name: "Pocket Ringtail", size: 16 },
];
const STATE_NAMES = { walk_right: "walkRight", walk_left: "walkLeft" };

function fail(message) {
	console.error(message);
	process.exit(1);
}

function readJson(path) {
	try {
		return JSON.parse(readFileSync(path, "utf8"));
	} catch (error) {
		fail(`Cannot read ${path}: ${error instanceof Error ? error.message : String(error)}`);
	}
}

function parseHex(key, hex) {
	const match = typeof hex === "string" ? /^#([0-9a-f]{6})$/i.exec(hex) : null;
	if (!match) fail(`Invalid color for key ${JSON.stringify(key)}: ${JSON.stringify(hex)}`);
	const value = Number.parseInt(match[1], 16);
	return [(value >> 16) & 255, (value >> 8) & 255, value & 255];
}

function palette(pack) {
	if (pack.transparent !== "." || pack.palette?.["."] !== null) fail("Expected \".\" as the transparent key");
	const entries = Object.entries(pack.palette).filter(([key]) => key !== ".");
	for (const [key] of entries) {
		if (key.length !== 1 || key === "\"" || key === "\\") fail(`Unsupported palette key ${JSON.stringify(key)}`);
	}
	return Object.fromEntries(entries.map(([key, hex]) => [key, parseHex(key, hex)]));
}

function animation(variant, state, size, colors) {
	const entry = variant.animations?.[state];
	if (!entry || !Array.isArray(entry.frames) || entry.frames.length === 0) fail(`${size}: missing state ${state}`);
	if (!Array.isArray(entry.duration_ms) || entry.duration_ms.length !== entry.frames.length) {
		fail(`${size} ${state}: expected one duration per frame`);
	}
	for (const duration of entry.duration_ms) {
		if (!Number.isInteger(duration) || duration <= 0) fail(`${size} ${state}: invalid duration ${JSON.stringify(duration)}`);
	}
	for (const frame of entry.frames) {
		if (!Array.isArray(frame) || frame.length !== size) fail(`${size} ${state}: expected ${size} rows`);
		for (const row of frame) {
			if (typeof row !== "string" || row.length !== size) fail(`${size} ${state}: expected ${size} columns`);
			for (const key of row) {
				if (key !== "." && !(key in colors)) fail(`${size} ${state}: unknown key ${JSON.stringify(key)}`);
			}
		}
	}
	return entry;
}

function variantStates(pack, { key, size }, colors) {
	const variant = pack.variants?.[key];
	if (!variant || variant.width !== size || variant.height !== size) fail(`Expected the ${size} x ${size} variant`);
	const idle = animation(variant, "idle", size, colors);
	const rest = idle.frames[0];
	const states = { idle: { durationsMs: [idle.duration_ms[0]], frames: [rest] } };
	for (const state of ACTIVE_STATES) {
		const entry = animation(variant, state, size, colors);
		const kept = { durationsMs: [], frames: [] };
		entry.frames.forEach((frame, index) => {
			if (frame.join("\n") === rest.join("\n")) return;
			kept.frames.push(frame);
			kept.durationsMs.push(entry.duration_ms[index]);
		});
		if (kept.frames.length === 0) fail(`${size} ${state}: every frame repeats the idle pose`);
		states[STATE_NAMES[state] ?? state] = kept;
	}
	return states;
}

function moduleSource(colors, variants) {
	const lines = [
		"// Generated by scripts/generate-pi-slim-sprites.mjs from pi-terminal-v2/frames.json. Do not edit by hand.",
		"// Grids hold palette keys, \".\" for transparent; each terminal row shows two grid rows.",
		"",
		"import type { PixelRgb } from \"./pi-raccoon-sprites.js\";",
		"",
		"export const PI_SLIM_PALETTE: Readonly<Record<string, PixelRgb>> = {",
		...Object.entries(colors).map(([key, [r, g, b]]) => `\t"${key}": [${r}, ${g}, ${b}],`),
		"};",
	];
	for (const { constant, name, size, states } of variants) {
		lines.push(
			"",
			`/** ${name} companion animations, ${size} x ${size} pixels each, with one duration per frame. Idle keeps its resting frame. */`,
			`export const ${constant} = {`,
		);
		for (const [state, { durationsMs, frames: grids }] of Object.entries(states)) {
			lines.push(`\t${state}: {`, `\t\tdurationsMs: [${durationsMs.join(", ")}],`, "\t\tframes: [");
			for (const grid of grids) lines.push("\t\t\t[", ...grid.map((row) => `\t\t\t\t"${row}",`), "\t\t\t],");
			lines.push("\t\t],", "\t},");
		}
		lines.push("} as const;");
	}
	lines.push("");
	return lines.join("\n");
}

const [framesPath, outFile] = process.argv.slice(2);
if (!framesPath || !outFile) fail("Usage: node scripts/generate-pi-slim-sprites.mjs <frames.json> <out-file>");

const pack = readJson(framesPath);
if (pack.name !== "Pi — slim raccoon animations" || pack.version !== 2) {
	fail("Expected the Pi Terminal v2 frames.json (slim raccoon animations), version 2");
}
const colors = palette(pack);
const variants = VARIANTS.map((variant) => ({ ...variant, states: variantStates(pack, variant, colors) }));
writeFileSync(outFile, moduleSource(colors, variants));
console.log(`Wrote ${outFile}`);
